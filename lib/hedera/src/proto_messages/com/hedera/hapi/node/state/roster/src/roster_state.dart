    );
  }

  factory HederaRoundRosterPair.deserialize(List<int> bytes) {
    final decode = HederaProtoMessage.decode(bytes, protoConfigStatic());
    return HederaRoundRosterPair(
      roundNumber: decode.getBigInt<BigInt?>(1),
      activeRosterHash: decode.getBytes<List<int>?>(2),
    );
  }

  @override
DefaultHederaProtoTypeUrl get declarationId => DefaultHederaProtoTypeUrl.comHederaHapiNodeStateRosterRoundRosterPair;

}


